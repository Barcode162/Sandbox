void fontCell(char c, int& column, int& row) {
  if (c < font::kFirstChar || c > font::kLastChar) c = '?';
  const int index = c - font::kFirstChar;
  column = index % font::kColumns;
  row = index / font::kColumns;
}

void shapeCell(int shape, int& column, int& row) {
  const int index = font::kGlyphCount + shape;
  column = index % font::kColumns;
  row = index / font::kColumns;
}

FontAtlas buildFontAtlas(int mipLevels) {
  using namespace font;
  constexpr int S = kTexelsPerPixel;
  constexpr int cellTexW = kCellW * S, cellTexH = kCellH * S;
  FontAtlas atlas;
  atlas.width = kColumns * cellTexW;
  atlas.height = kRows * cellTexH;
  std::vector<uint8_t> base(atlas.width * atlas.height, 0);

  // Is font pixel (x, y) of a glyph filled? Outside the 5x9 area is empty.
  auto filled = [](const GlyphArt& g, int x, int y) {
    if (x < 0 || y < 0 || x >= kGlyphW || y >= kGlyphH || !g.rows[y]) return false;
    return g.rows[y][x] == '#';
  };

  for (const GlyphArt& g : kGlyphs) {
    int col, row;
    fontCell(g.c, col, row);
    for (int ty = 0; ty < cellTexH; ++ty) {
      for (int tx = 0; tx < cellTexW; ++tx) {
        // Texel center in glyph pixel space (the glyph starts at kPad).
        const float px = (static_cast<float>(tx) + 0.5f) / S - kPad;
        const float py = (static_cast<float>(ty) + 0.5f) / S - kPad;
        const int cx = static_cast<int>(std::floor(px)), cy = static_cast<int>(std::floor(py));
        const bool inside = filled(g, cx, cy);
        // Exact distance to the nearest pixel of the opposite kind. The SDF only
        // needs +-kSdfRange, so checking neighbors within 2 pixels is enough.
        float best = 1e9f;
        for (int y = cy - 2; y <= cy + 2; ++y) {
          for (int x = cx - 2; x <= cx + 2; ++x) {
            if (filled(g, x, y) == inside) continue;
            best = std::min(best, distanceToSquare(px, py, static_cast<float>(x), static_cast<float>(y)));
          }
        }
        const float signedDist = inside ? best : -best;
        const float v = std::clamp(0.5f + 0.5f * signedDist / kSdfRange, 0.0f, 1.0f);
        base[(row * cellTexH + ty) * atlas.width + col * cellTexW + tx] =
            static_cast<uint8_t>(std::lround(v * 255.0f));
      }
    }
  }
  // The round shapes, as exact distance fields.
  for (int shape = 0; shape < kShapeCount; ++shape) {
    int col, row;
    shapeCell(shape, col, row);
    for (int ty = 0; ty < cellTexH; ++ty) {
      for (int tx = 0; tx < cellTexW; ++tx) {
        const float px = (static_cast<float>(tx) + 0.5f) / S - kShapeCenterX;
        const float py = (static_cast<float>(ty) + 0.5f) / S - kShapeCenterY;
        const float d = std::sqrt(px * px + py * py);
        float signedDist = kShapeRadius - d;
        if (shape == kShapeRing) signedDist = std::min(signedDist, d - kRingInner);
        const float v = std::clamp(0.5f + 0.5f * signedDist / kSdfRange, 0.0f, 1.0f);
        base[(row * cellTexH + ty) * atlas.width + col * cellTexW + tx] = static_cast<uint8_t>(std::lround(v * 255.0f));
      }
    }
  }
  atlas.mips.push_back(std::move(base));

  // Smaller copies for far-away / small text: average each 2x2 block. Cell
  // sizes are multiples of 8 texels, so glyphs never bleed into each other
  // for the first 3 smaller levels.
  uint32_t w = atlas.width, h = atlas.height;
  for (int level = 1; level < mipLevels; ++level) {
    const std::vector<uint8_t>& src = atlas.mips.back();
    const uint32_t nw = w / 2, nh = h / 2;
    std::vector<uint8_t> dst(nw * nh);
    for (uint32_t y = 0; y < nh; ++y) {
      for (uint32_t x = 0; x < nw; ++x) {
        const uint32_t i = 2 * y * w + 2 * x;
        dst[y * nw + x] = static_cast<uint8_t>((src[i] + src[i + 1] + src[i + w] + src[i + w + 1] + 2) / 4);
      }
    }
    atlas.mips.push_back(std::move(dst));
    w = nw;
    h = nh;
  }
  return atlas;
}

